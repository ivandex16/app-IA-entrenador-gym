const mongoose = require('mongoose');
const { ALL_STATUSES, WORKOUT_STATUS } = require('../constants/workoutStatus');

const setLogSchema = new mongoose.Schema(
  {
    setNumber: { type: Number, required: true },
    reps: { type: Number, required: true },
    weight: { type: Number, default: 0 },   // kg
    rpe: { type: Number, min: 1, max: 10 }, // rate of perceived exertion
    // Marked done during a live session. Absent on legacy/manual entries, where
    // every listed set counts as done. Lets an unfinished session show progress.
    completed: { type: Boolean },
    // Rest actually taken AFTER this set (seconds). Optional: only when the rest
    // timer ran; absent on legacy sessions.
    restSeconds: { type: Number, min: 0, max: 1800 },
  },
  { _id: false }
);

const exerciseLogSchema = new mongoose.Schema(
  {
    exercise: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Exercise',
      required: true,
    },
    // Planned rest between this exercise's sets (seconds): from the routine or
    // the session setting. Per-set `restSeconds` holds what was really taken.
    restSeconds: { type: Number, min: 0, max: 1800 },
    sets: [setLogSchema],
  },
  { _id: false }
);

const workoutLogSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    routine: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Routine',
    },
    date: { type: Date, default: Date.now },
    durationMinutes: { type: Number, default: 0 },
    exercises: [exerciseLogSchema],
    notes: { type: String, default: '' },
    feeling: {
      type: String,
      enum: ['great', 'good', 'ok', 'tired', 'bad'],
      default: 'good',
    },
    caloriesBurned: { type: Number, default: 0 },
    // Starred by the user in the history to find key sessions quickly.
    favorite: { type: Boolean, default: false },
    // Real lifecycle state (see constants/workoutStatus.js). Default COMPLETED
    // keeps old clients working: they only ever posted finished sessions.
    status: { type: String, enum: ALL_STATUSES, default: WORKOUT_STATUS.COMPLETED },
    startedAt: { type: Date },      // when the live session started
    endedAt: { type: Date },        // when it was completed or cancelled
    activeSeconds: { type: Number, min: 0 }, // time trained, pauses excluded (used to resume)
    // Id generated by the client for each workout session. Makes POST idempotent:
    // a double tap or a retry after a timeout returns the same log instead of a copy.
    clientId: { type: String, trim: true, maxlength: 64 },
  },
  { timestamps: true }
);

workoutLogSchema.index({ user: 1, date: -1, _id: -1 });
workoutLogSchema.index({ user: 1, status: 1, date: -1 });
workoutLogSchema.index(
  { user: 1, clientId: 1 },
  { unique: true, partialFilterExpression: { clientId: { $type: 'string' } } }
);

module.exports = mongoose.model('WorkoutLog', workoutLogSchema);
